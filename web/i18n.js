// UI strings for every language the site speaks — no DOM, no fetch,
// unit-tested via node --test. German is the default; the picker lists LANGS.
// The legal pages (Impressum, Datenschutz) stay German-only by design. Values may
// carry trusted markup (<b>, <a>, <code>) — they are constants from this file,
// never user input; anything interpolated into {tokens} must be escaped by the
// caller.

// At least one official language of every swept country, plus English.
// de/en/da came first; nl, fr, it, cs, pl and sv arrived with the UK and
// France; the 22 from bs to uk arrived with the Europe-complete ring. Order is
// the order the picker lists them in: German first because the site is
// German-first, then each arrival group by endonym.
// Deliberately absent, all on the Romansh precedent (no monolingual readers —
// every speaker reads another UI language): Romansh itself, Luxembourgish
// (fr/de), Maltese and Irish (en), Montenegrin (mutually intelligible with
// sr/hr/bs), and Turkish for Cyprus (the swept republic's public signage
// pairs el with en).
